/** The events a voice knows. */
export const EVENTS = Object.keys(L.joviaal);

/**
 * A line of the voice for an event. `ctx`: { fx, tier, friend }. `rand` picks the variant
 * (inject it in tests). A voice without the event falls back to the cheerful one.
 */
export function lineFor(voice, event, ctx = {}, rand = Math.random) {
  const list = (L[voice] ?? L.joviaal)[event] ?? L.joviaal[event] ?? [''];
  const text = list[Math.floor(rand() * list.length) % list.length];
  return text.replace('{fx}', (ctx.fx ?? 'dit').toLowerCase()).replace('{tier}', (ctx.tier ?? '').toLowerCase()).replace('{friend}', ctx.friend ?? 'een vriend');
}

