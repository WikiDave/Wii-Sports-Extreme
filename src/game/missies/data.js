/** Open-ended missions after the chain: k = 1, 2, ... (endless, the goal grows with k). */
export function openMission(k) {
  const n = Math.max(1, k);
  const kinds = [
    { goal: { kind: 'verkoop', n: 150 * n }, text: `Verkoop ${150 * n} stuks.` },
    { goal: { kind: 'verdien', n: 5000 * n }, text: `Verdien €${(5000 * n).toLocaleString('nl-NL')} in totaal.` },
    { goal: { kind: 'gemaakt', product: null, n: 20 * n }, text: `Start ${20 * n} batches.` },
    { goal: { kind: 'zwem', n: 300 * n }, text: `Zwem ${300 * n} meter.` },
  ];
  const pick = kinds[(n - 1) % kinds.length];
  return {
    id: `vrij-${n}`,
    title: `Vrije opdracht ${n}`,
    goal: pick.goal,
    hint: pick.text,
    intro: [`Nog een klus, lieverd. Je kunt het blijkbaar. Deze keer: ${pick.text.toLowerCase()}`],
    nudge: ['Nog niet klaar. Ik tel mee, hoor.'],
    done: ['Klaar! Jij bent niet te stoppen, hè?'],
    reward: { cash: 800 * n, xp: 100 * n, points: n % 2 === 0 ? 1 : 0 },
    open: true,
  };
}

